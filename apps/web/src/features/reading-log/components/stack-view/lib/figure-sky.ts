export function drawCloud(p: Pencil, variant: number) {
  const art = CLOUDS[variant % CLOUDS.length];
  p.fill(art.body);
  p.fill(art.belly, BELLY_TONE);
  const hatch: Cmds = [];
  for (let x = art.hatch[0]; x <= art.hatch[1]; x += 13)
    hatch.push("M", x, 90, "L", x + 9, 81);
  p.hatch(hatch, { op: 0.3 });
  p.pen(art.folds, { w: 1.1, light: false, op: 0.55 });
  p.pen(art.body, { w: 1.5, a: 0.7 });
}
